/* M618. CLAUDE.md's channel list, GENERATED from src/shared/ipc-contract.ts.
   Before M618 the list was copied by hand, so adding a channel meant editing
   the contract, preload, main's handler, and then this list too; a forgotten
   copy turned verify:meta claude-md.1 red with nothing to say what to run.
   Now the list is every IPC (invoke) channel followed by every IPC_EVENTS
   channel, in contract order, wrapped at WIDTH, between two markers:

     npm run ipc:list            rewrite the block in CLAUDE.md
     node scripts/ipc-list.cjs   print the block, change nothing

   verify:meta ipc-list.1 goes red when the block and the contract disagree.
   The preload bridge stays hand-written ON PURPOSE: most entries shape
   their arguments or answer on a reply channel, and that is what its
   comments explain. Only this list was pure bookkeeping. */
'use strict'
const { buildSync } = require('esbuild')
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs')
const { join } = require('node:path')

const ROOT = join(__dirname, '..')
const CLAUDE_MD = join(ROOT, 'CLAUDE.md')
const START = '<!-- ipc:channels (generated by `npm run ipc:list` from src/shared/ipc-contract.ts; do not edit by hand) -->'
const END = '<!-- /ipc:channels -->'
const WIDTH = 95

function contractChannels() {
  const out = join(ROOT, 'out', 'verify', 'ipc-list-contract.cjs')
  mkdirSync(join(ROOT, 'out', 'verify'), { recursive: true })
  buildSync({ entryPoints: [join(ROOT, 'src', 'shared', 'ipc-contract.ts')], bundle: true, platform: 'node', format: 'cjs', outfile: out, logLevel: 'error' })
  delete require.cache[out]
  const c = require(out)
  return [...Object.values(c.IPC), ...Object.values(c.IPC_EVENTS)]
}

function wrap(words) {
  const lines = []
  let line = ''
  for (const w of words) {
    if (line !== '' && line.length + 1 + w.length > WIDTH) { lines.push(line); line = w } else line = line === '' ? w : `${line} ${w}`
  }
  if (line !== '') lines.push(line)
  return lines.join('\n')
}

/** The whole marked block, fences included. */
function block() {
  return `${START}\n\`\`\`\n${wrap(contractChannels())}\n\`\`\`\n${END}`
}

/** The block as CLAUDE.md holds it now, or null when the markers are missing. */
function currentBlock(text) {
  const a = text.indexOf(START)
  const b = text.indexOf(END)
  return a < 0 || b < a ? null : text.slice(a, b + END.length)
}

module.exports = { block, currentBlock, contractChannels, START, END }

if (require.main === module) {
  const want = block()
  if (!process.argv.includes('--write')) { process.stdout.write(`${want}\n`); process.exit(0) }
  // Read BEFORE writing: M47 emptied CLAUDE.md with a script that did not.
  const text = readFileSync(CLAUDE_MD, 'utf8')
  const have = currentBlock(text)
  if (have === null) { console.error(`CLAUDE.md has no ${START.slice(0, 20)}… marker pair; add one around the channel list first.`); process.exit(1) }
  if (have === want) { console.log('CLAUDE.md channel list already matches the contract.'); process.exit(0) }
  writeFileSync(CLAUDE_MD, text.replace(have, want))
  console.log('CLAUDE.md channel list rewritten from the contract.')
}
