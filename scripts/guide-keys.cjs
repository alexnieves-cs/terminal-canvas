/* M632. The user guide's shortcut tables, GENERATED from
   src/shared/shortcuts.ts, the one list Settings › Keyboard, the app menu and
   the canvas listeners read. The README's old keyboard table was written by
   hand in M2 and still said ⌘N was "New panel" three redesigns later; a
   second hand-kept list is how that happens.

     npm run guide:keys            rewrite the block in docs/guide/keyboard.md
     node scripts/guide-keys.cjs   print the block, change nothing

   verify:meta guide.keys.1 goes red when the block and the registry disagree.
   The registry is read as TEXT, one row per line, so this needs no build and
   no esbuild: the Pages job and a plain-node suite both run it. A row the
   pattern cannot read is caught by the count guide.keys.1 compares. */
'use strict'
const { readFileSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')

const ROOT = join(__dirname, '..')
const PAGE = join(ROOT, 'docs', 'guide', 'keyboard.md')
const START = '<!-- guide:keys (generated by `npm run guide:keys` from src/shared/shortcuts.ts; do not edit by hand) -->'
const END = '<!-- /guide:keys -->'
// The registry's own groups, in reading order, under a reader's heading.
const GROUPS = [
  ['create', 'Create'],
  ['sessions', 'Agents and attention'],
  ['navigate', 'Move around'],
  ['existing', 'Edit and arrange'],
  ['mouse', 'Mouse and trackpad']
]

function rows() {
  const src = readFileSync(join(ROOT, 'src', 'shared', 'shortcuts.ts'), 'utf8')
  const list = src.slice(src.indexOf('export const SHORTCUTS'), src.indexOf('export const SHORTCUT_HANDLERS'))
  const out = []
  for (const m of list.matchAll(/^\s*\{ id: '([^']+)', chord: '((?:[^'\\]|\\.)+)', scope: '([^']+)', group: '([^']+)', label: '((?:[^'\\]|\\.)+)'(, aliasOf: '[^']+')? \},?$/gm)) {
    const unescape = (s) => s.replace(/\\(.)/g, '$1')
    out.push({ id: m[1], chord: unescape(m[2]), scope: m[3], group: m[4], label: unescape(m[5]), alias: m[6] !== undefined })
  }
  return out
}

/** How many rows the registry declares, counted with a looser pattern than `rows` reads with. */
function declared() {
  const src = readFileSync(join(ROOT, 'src', 'shared', 'shortcuts.ts'), 'utf8')
  const list = src.slice(src.indexOf('export const SHORTCUTS'), src.indexOf('export const SHORTCUT_HANDLERS'))
  return [...list.matchAll(/^\s*\{ id: '/gm)].length
}

function block() {
  const all = rows().filter((r) => !r.alias)
  const parts = [START]
  for (const [group, heading] of GROUPS) {
    const mine = all.filter((r) => r.group === group)
    if (mine.length === 0) continue
    parts.push(`### ${heading}`, '', '| Keys | What it does |', '|---|---|')
    // A pipe inside a table cell ends the cell; ⌘\ is a real chord.
    for (const r of mine) parts.push(`| \`${r.chord}\` | ${r.label}${r.scope === 'panel' ? ' (in a focused terminal)' : ''} |`)
    parts.push('')
  }
  parts.push(END)
  return parts.join('\n')
}

function currentBlock(text) {
  const a = text.indexOf(START)
  const b = text.indexOf(END)
  return a < 0 || b < a ? null : text.slice(a, b + END.length)
}

module.exports = { block, currentBlock, rows, declared, GROUPS, START, END }

if (require.main === module) {
  const want = block()
  if (!process.argv.includes('--write')) { console.log(want); process.exit(0) }
  const text = readFileSync(PAGE, 'utf8')
  const have = currentBlock(text)
  if (have === null) { console.error('docs/guide/keyboard.md has lost its guide:keys markers'); process.exit(1) }
  if (have !== want) writeFileSync(PAGE, text.replace(have, want))
  console.log(have === want ? 'docs/guide/keyboard.md is already current' : 'docs/guide/keyboard.md rewritten from src/shared/shortcuts.ts')
}
